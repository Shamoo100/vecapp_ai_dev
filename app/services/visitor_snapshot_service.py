class VisitorSnapshotService:
    """Service for generating visitor snapshots with AI-powered summaries"""
    
    def __init__(self, schema_name: str):
        """Initialize the visitor snapshot service
        
        Args:
            schema_name: The tenant-specific schema name
        """
        self.schema_name = schema_name
        self.member_service = MemberService(schema_name)
        self.followup_agent = FollowupNoteAgent(f"visitor_snapshot_{schema_name}", "v1")
        self.context_builder = VisitorContextBuilder(schema_name)
        
    async def initialize(self) -> None:
        """Initialize the service and its dependencies"""
        await self.member_service.initialize()
        logger.info(f"Visitor snapshot service initialized for schema: {self.schema_name}")
    
