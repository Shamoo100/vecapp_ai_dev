    async def _fetch_visitors_by_date_range(
        self, 
        tenant_id: str, 
        start_date: Optional[datetime], 
        end_date: Optional[datetime]
    ) -> List[PersonProfile]:
        """Fetch visitors within the specified date range"""
        try:
            # Calculate date range if not provided
            if not start_date or not end_date:
                end_date = datetime.now(timezone.utc)
                start_date = end_date - timedelta(days=90)  # Default to last 90 days
            
            # Get visitors from member service
            visitors = await self.member_service.get_visitors_by_date_range(
                start_date=start_date,
                end_date=end_date,
                limit=1000  # Get more than needed for accurate pagination
            )
            
            return visitors
            
        except Exception as e:
            logger.error(f"Error fetching visitors by date range: {e}")
            raise
    
    def _group_visitors_by_family(self, visitors: List[PersonProfile]) -> Dict[str, List[PersonProfile]]:
        """Group visitors by family ID
        
        Args:
            visitors: List of visitor profiles
            
        Returns:
            Dictionary mapping family keys to lists of family members
        """
        family_groups = {}
        
        for visitor in visitors:
            # Use fam_id if available, otherwise treat as individual family
            family_key = str(visitor.fam_id) if visitor.fam_id else f"individual_{visitor.id}"
            
            if family_key not in family_groups:
                family_groups[family_key] = []
            family_groups[family_key].append(visitor)
        
        return family_groups
    
    # =============================================================================
    # FAMILY PROCESSING METHODS
