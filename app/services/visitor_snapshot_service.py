    # MAIN PUBLIC METHODS
    # =============================================================================
    
    async def get_visitor_snapshots(
        self,
        request: VisitorSnapshotRequest,
        tenant_id: str
    ) -> VisitorSnapshotResponse:
        """Generate visitor snapshots with enhanced criteria support"""
        try:
            # Fetch visitors based on date range
            visitors = await self._fetch_visitors_by_date_range(
                tenant_id, 
                request.date_range_start, 
                request.date_range_end
            )
            
            if not visitors:
                return VisitorSnapshotResponse(
                    entries=[],
                    total_count=0,
                    page=request.page,
                    has_more=False,
                    ai_disclaimer="No visitors found for the specified criteria."
                )
            
            # Apply family grouping based on criteria
            if request.family_criteria == FamilyCriteria.GROUPED_BY_FAMILY:
                grouped_visitors = self._group_visitors_by_family(visitors)
                summary_entries = await self._create_family_summary_entries_concurrent(
                    list(grouped_visitors.values()), 
                    tenant_id,
                    request.note_criteria,
                    request.report_purpose
                )
            else:
                # Individual processing
                summary_entries = await self._create_individual_summary_entries_concurrent(
                    visitors,
                    tenant_id, 
                    request.note_criteria,
                    request.report_purpose
                )
            
            # Apply pagination
            total_count = len(summary_entries)
            start_idx = (request.page - 1) * request.limit
            end_idx = start_idx + request.limit
            paginated_entries = summary_entries[start_idx:end_idx]
            
            has_more = end_idx < total_count
            
            return VisitorSnapshotResponse(
                entries=paginated_entries,
                total_count=total_count,
                page=request.page,
                has_more=has_more,
                ai_disclaimer="This summary was generated by AI and may not capture all nuances. Please review the full visitor context for complete information."
            )
            
        except Exception as e:
            logger.error(f"Error generating visitor snapshots: {str(e)}")
            raise
    
    # =============================================================================
    # DATA FETCHING METHODS
