    def _create_fallback_family_entry(
        self, 
        family_members: List[PersonProfile],
        report_purpose: Optional[str]
    ) -> VisitorSummaryEntry:
        """Create a fallback visitor entry when family processing fails
        
        Args:
            family_members: List of family member profiles
            report_purpose: Purpose of the report
            
        Returns:
            Basic VisitorSummaryEntry for the family
        """
        primary_visitor = family_members[0]
        family_member_names = [f"{member.first_name} {member.last_name}" for member in family_members]
        contact_person = f"{primary_visitor.first_name} {primary_visitor.last_name}"
        
        return VisitorSummaryEntry(
            visitor_id=primary_visitor.id,
            name=f"{contact_person} Family" if len(family_members) > 1 else contact_person,
            first_visit_date=primary_visitor.created_at,
            family_size=len(family_members),
            family_members=family_member_names,
            contact_person=contact_person,
            visitor_summary=self._create_fallback_family_summary(family_members, primary_visitor),
            sentiment_classification="Neutral",
            notes_scope_used="Basic family visitor profile data",
            report_purpose=report_purpose or "Family visitor follow-up and engagement tracking",
            is_expanded=False
        )
    
    def _create_fallback_family_summary(
        self, 
        family_members: List[PersonProfile], 
        primary_visitor: PersonProfile
    ) -> str:
        """Create a fallback summary when family AI generation fails
        
        Args:
            family_members: List of family member profiles
            primary_visitor: The primary contact person
            
        Returns:
            Basic fallback summary for the family
        """
        if len(family_members) == 1:
            name = f"{primary_visitor.first_name} {primary_visitor.last_name}"
            visit_date = primary_visitor.created_at.strftime("%B %d, %Y") if primary_visitor.created_at else "recently"
            return f"{name} visited our church {visit_date}. They are a new visitor to our community and we look forward to connecting with them further."
